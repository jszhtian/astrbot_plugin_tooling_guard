"""Fixed 22-key trajectory summary schema.

Requirement: Trajectory Summary Record; Argument Digesting.

Callers pass already-redacted strings for summary_line; redaction itself belongs
to tooling_guard.anonymize. This module only enforces structure and the two
length caps, so a summary can never grow past the spec bound.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

from .intent import args_digest as digest_arguments
from .intent import canonical_arguments

TRAJECTORY_KEYS: tuple[str, ...] = (
    "ts_seq",
    "call_id",
    "at",
    "user",
    "session",
    "tool",
    "origin",
    "verb",
    "targets",
    "tier",
    "args_digest",
    "args_head",
    "content_len",
    "content_lines",
    "rule_hits",
    "single",
    "links",
    "summary_line",
    "decision",
    "ticket",
    "labels",
    "delegated",
)

SUMMARY_LINE_LIMIT = 160
ARGS_HEAD_LIMIT = 512
TIER_STRONG = "T-strong"


def truncate(text: str, limit: int) -> str:
    """Return text truncated to at most limit characters.

    Requirement: Trajectory Summary Record.
    """
    return text if len(text) <= limit else text[:limit]


def utc_now_text() -> str:
    """Return the current UTC instant as an ISO-8601 string.

    Requirement: Trajectory Summary Record.
    """
    return datetime.now(UTC).isoformat(timespec="milliseconds")


def line_count(text: str) -> int:
    """Return the number of lines in text, or 0 for empty text.

    Requirement: Trajectory Summary Record.
    """
    return 0 if not text else text.count("\n") + 1


@dataclass(frozen=True, slots=True)
class CallSummary:
    """One spec-conforming trajectory summary with explicit nulls.

    Requirement: Trajectory Summary Record.

    The 22 attributes are the 22 required keys in spec order; unknown values are
    None and are never omitted from as_dict.
    """

    ts_seq: int
    call_id: str
    at: str
    user: str | None
    session: str | None
    tool: str
    origin: str | None
    verb: str | None
    targets: tuple[str, ...]
    tier: str
    args_digest: str
    args_head: str
    content_len: int | None
    content_lines: int | None
    rule_hits: tuple[str, ...]
    single: Mapping[str, Any] | None
    links: tuple[str, ...]
    summary_line: str
    decision: str | None
    ticket: str | None
    labels: frozenset[str]
    delegated: str | None

    def __post_init__(self) -> None:
        """Normalize containers and enforce the two length caps.

        Requirement: Trajectory Summary Record.
        """
        object.__setattr__(self, "targets", tuple(self.targets))
        object.__setattr__(self, "rule_hits", tuple(self.rule_hits))
        object.__setattr__(self, "links", tuple(self.links))
        object.__setattr__(self, "labels", frozenset(self.labels))
        object.__setattr__(
            self, "single", None if self.single is None else dict(self.single)
        )
        object.__setattr__(self, "args_head", truncate(self.args_head, ARGS_HEAD_LIMIT))
        object.__setattr__(
            self, "summary_line", truncate(self.summary_line, SUMMARY_LINE_LIMIT)
        )

    def as_dict(self) -> dict[str, Any]:
        """Return all 22 keys, in spec order, with explicit nulls.

        Requirement: Trajectory Summary Record.
        """
        return {key: getattr(self, key) for key in TRAJECTORY_KEYS}


def summarize_call(
    *,
    ts_seq: int,
    call_id: str,
    tool: str,
    at: str | None = None,
    user: str | None = None,
    session: str | None = None,
    origin: str | None = None,
    verb: str | None = None,
    targets: Iterable[str] = (),
    tier: str = TIER_STRONG,
    arguments: Mapping[str, Any] | None = None,
    args_digest: str | None = None,
    args_head: str | None = None,
    content: str | None = None,
    content_len: int | None = None,
    content_lines: int | None = None,
    rule_hits: Iterable[str] = (),
    single: Mapping[str, Any] | None = None,
    links: Iterable[str] = (),
    summary_line: str = "",
    decision: str | None = None,
    ticket: str | None = None,
    labels: Iterable[str] = (),
    delegated: str | None = None,
) -> CallSummary:
    """Build one 22-key summary for a managed call.

    Requirement: Trajectory Summary Record; Argument Digesting.

    Unknown inputs stay None so every record keeps all 22 keys. The digest and
    head are derived from arguments unless supplied explicitly, and
    summary_line/args_head are truncated to 160/512 characters.

    Args:
        ts_seq: Trajectory ordering sequence for the subject.
        call_id: UUID generated by the intent recorder.
        tool: Managed tool name.
        at: ISO-8601 wall-clock text; defaults to the current UTC instant.
        user: platform_id:sender_id identity.
        session: Minimal conversation correlation key.
        origin: Message origin (platform or chat) when known.
        verb: Normalized tool verb when known.
        targets: Normalized targets extracted by the triage layer.
        tier: T-strong or T-weak; unknown stays T-strong.
        arguments: Call arguments used to derive digest and head.
        args_digest: Precomputed digest, overriding arguments.
        args_head: Precomputed bounded head, overriding arguments.
        content: Tool result text used to derive length and line count.
        content_len: Precomputed result length in characters.
        content_lines: Precomputed result line count.
        rule_hits: Deterministic rule identifiers that matched.
        single: Single-call judgement record (risk, categories, confidence).
        links: Related call_id values (intent, ticket, retry).
        summary_line: Already-redacted one-line summary, at most 160 characters.
        decision: Catalogued decision value, or None before a decision.
        ticket: Approval ticket marker, or None.
        labels: Orthogonal labels such as sink_read or untrusted_source.
        delegated: Delegation path for the executed call, or None.

    Returns:
        CallSummary: The normalized summary record.
    """
    resolved_digest = (
        args_digest if args_digest is not None else digest_arguments(arguments)
    )
    resolved_head = args_head
    if resolved_head is None:
        resolved_head = (
            truncate(canonical_arguments(arguments), ARGS_HEAD_LIMIT)
            if arguments is not None
            else ""
        )
    resolved_len = content_len
    resolved_lines = content_lines
    if content is not None:
        if resolved_len is None:
            resolved_len = len(content)
        if resolved_lines is None:
            resolved_lines = line_count(content)
    return CallSummary(
        ts_seq=ts_seq,
        call_id=call_id,
        at=at if at is not None else utc_now_text(),
        user=user,
        session=session,
        tool=tool,
        origin=origin,
        verb=verb,
        targets=tuple(targets),
        tier=tier,
        args_digest=resolved_digest,
        args_head=resolved_head,
        content_len=resolved_len,
        content_lines=resolved_lines,
        rule_hits=tuple(rule_hits),
        single=single,
        links=tuple(links),
        summary_line=summary_line,
        decision=decision,
        ticket=ticket,
        labels=frozenset(labels),
        delegated=delegated,
    )
